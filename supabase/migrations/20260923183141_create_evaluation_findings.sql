-- Migration: Create public.evaluation_findings table
-- Date: 2026-09-23
-- Purpose: Persist an explicitly captured snapshot of BIM-Guard's PASS/FAIL
-- verdict for one rule against one IFC element, alongside a human reviewer's
-- confirmed/overridden verdict for the same test. This is the ground-truth
-- data the separate bim-guard-evaluation companion repo scores (confusion
-- matrix / accuracy / precision / recall / F1) via the API -- bim-guard
-- itself only stores the two verdicts side by side.
--
-- Compliance results are otherwise never persisted (see
-- app/services/analysis_cache.py: recomputed on demand, cached in-process
-- only), so without this table there is nothing for a human to review after
-- the fact. Rows are only written by an explicit "capture for evaluation"
-- action (POST /api/evaluation/capture), not by every analysis run, keeping
-- the evaluation set curated rather than an unbounded firehose.
--
-- Append-only by design: re-capturing the same rule/element inserts a new
-- row rather than overwriting, so a past reviewer decision stays attached to
-- the run it was made against. rule_snapshot freezes the rule fields that
-- were actually graded, since public.rules has no version history and a
-- later edit must not retroactively change what an old finding was tested
-- against.
--
-- Idempotent: safe to re-run.

BEGIN;

CREATE TABLE IF NOT EXISTS public.evaluation_findings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          BIGINT NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    ifc_file_id         BIGINT REFERENCES public.project_ifc_files(id) ON DELETE SET NULL,
    rule_id             BIGINT REFERENCES public.rules(id) ON DELETE SET NULL,
    rule_snapshot       JSONB NOT NULL,
    element_global_id   TEXT NOT NULL,
    element_name        TEXT,
    storey              TEXT,
    space               TEXT,
    bimguard_verdict    TEXT NOT NULL CHECK (bimguard_verdict IN (
        'PASS', 'FAIL', 'MISSING', 'WAIVED', 'NOT_APPLICABLE'
    )),
    bimguard_reason     TEXT,
    captured_by_email   TEXT,
    captured_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    human_verdict       TEXT CHECK (human_verdict IN (
        'PASS', 'FAIL', 'NOT_APPLICABLE', 'INDETERMINATE'
    )),
    reviewer_email      TEXT,
    reviewed_at         TIMESTAMP WITH TIME ZONE,
    review_notes        TEXT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_evaluation_findings_project_id
    ON public.evaluation_findings(project_id);
CREATE INDEX IF NOT EXISTS idx_evaluation_findings_rule_id
    ON public.evaluation_findings(rule_id);
CREATE INDEX IF NOT EXISTS idx_evaluation_findings_human_verdict
    ON public.evaluation_findings(human_verdict);

COMMENT ON TABLE  public.evaluation_findings IS
    'Human-validated ground truth for BIM-Guard PASS/FAIL verdicts, scored externally by bim-guard-evaluation';
COMMENT ON COLUMN public.evaluation_findings.rule_snapshot IS
    'Frozen copy of the rule fields graded at capture time (reference, operator, check_value/value_min/value_max, property_set/property_name, target_ifc_class, severity, unit, mechanism); public.rules has no version history';
COMMENT ON COLUMN public.evaluation_findings.bimguard_verdict IS
    'BIM-Guard''s own verdict at capture time, same vocabulary as ComplianceComparator._entry() status values';
COMMENT ON COLUMN public.evaluation_findings.human_verdict IS
    'Reviewer-confirmed correct verdict; NULL until reviewed. INDETERMINATE means the IFC lacked enough information to judge';

-- The app uses the service-role key, which bypasses RLS; enabling it denies
-- anon/authenticated clients by default (see rule_extraction_drafts migration).
ALTER TABLE public.evaluation_findings ENABLE ROW LEVEL SECURITY;

COMMIT;

