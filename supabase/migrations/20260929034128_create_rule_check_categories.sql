   SET check_category = m.check_category
  FROM public.rule_check_category_properties AS m
 WHERE r.check_category IS NULL
   AND lower(r.target_ifc_class) = lower(m.target_ifc_class)
   AND lower(r.property_name) = lower(m.property_name);

