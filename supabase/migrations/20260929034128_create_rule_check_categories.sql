-- Property -> category map. Rules are categorised from their target class and
-- property_name when no category is set explicitly (see
-- RuleCheckCategoryService.category_for_property). Seeded from the
-- "BIMGuard Window Properties - Functional Categories and Accuracy Table":
-- its 88 window properties, plus the IFC names some rules use for the same
-- values (OverallWidth/OverallHeight, SolarHeatGainTransmittance for SHGC,
-- GlassThickness1-3, IsTempered/IsLaminated).
CREATE TABLE IF NOT EXISTS public.rule_check_category_properties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_ifc_class text NOT NULL,
    property_name text NOT NULL,
    check_category text NOT NULL
        REFERENCES public.rule_check_categories (name) ON UPDATE CASCADE ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

