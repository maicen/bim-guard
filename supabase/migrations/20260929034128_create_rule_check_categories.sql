DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'rules_check_category_fkey'
    ) THEN
        ALTER TABLE public.rules
            ADD CONSTRAINT rules_check_category_fkey
            FOREIGN KEY (check_category)
            REFERENCES public.rule_check_categories (name)
            ON UPDATE CASCADE
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_rules_check_category
    ON public.rules (check_category);

