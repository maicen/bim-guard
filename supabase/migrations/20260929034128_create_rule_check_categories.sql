-- Migration: create_rule_check_categories
-- Date: 2026-09-29
-- Purpose: Analysis results are grouped per element type (Windows, Doors,
-- Stairs...) and, within each, by the topic a rule checks -- "Fire and Smoke
-- Protection", "Door Glazing Properties", "Guard Height and Edge Protection",
-- and so on. That topic list is data, not code: it lives here so it can be
-- renamed, reordered or extended without a deploy, and each rule points at
-- one entry via public.rules.check_category_id.
--
-- Categories belong to element types (target_ifc_classes; empty = every
-- type), and the same name may exist for different types -- the window,
-- door and stair tables each have their own "IFC Source, Units and
-- Coordinate Context" -- so rules reference a category by id, not by name.
--
-- check_category_id is distinct from the existing rules.rule_category column,
-- which classifies the check MECHANISM (property_check, threshold_band, ...).
--
-- Seeded from the user's BIMGuard property reliability tables: "Window
-- Properties - Functional Categories and Accuracy Table" (12 categories),
-- "Door Properties - Functional categories, extraction reliability and IFC
-- sources" (14) and "Stair, Handrail and Guardrail Properties" (22).
--
-- Idempotent: safe to re-run.

BEGIN;

CREATE TABLE IF NOT EXISTS public.rule_check_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    -- What the category tests; shown under its heading and given to the
    -- extraction LLM so it can tell neighbouring categories apart.
    description text NOT NULL DEFAULT '',
    -- Element types whose results this category groups; empty = every type.
    target_ifc_classes text[] NOT NULL DEFAULT '{}',
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_rule_check_categories_name_classes
    ON public.rule_check_categories (name, target_ifc_classes);

COMMENT ON TABLE public.rule_check_categories IS
    'Ordered check categories, per element type, used to group rule results in the analysis view.';

